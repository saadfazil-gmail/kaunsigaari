"""Find a free, credited photo for each car from Wikimedia Commons.

Writes photos.js: for each car, the image URL (hot-linked from Wikimedia,
nothing is downloaded), the photographer credit, the licence and a link to
the source page. Wikimedia images are free to use as long as we show credit.

For each car we search Wikipedia's file search with a query aimed at the
generation sold in Pakistan, and take the first photo that matches.

Run:  /usr/bin/python3 tools/fetch_photos.py
"""
import json
import re
import time
import urllib.parse
import urllib.request

API = "https://en.wikipedia.org/w/api.php"
UA = {"User-Agent": "gaari-mockup/0.1 (personal learning project)"}

# Car name on our site -> search words for the generation sold in Pakistan
QUERIES = {
    "Suzuki Alto": "Suzuki Alto 2015 front",
    "Toyota Corolla": "Toyota Corolla Altis E170 sedan",
    "Honda City": "Honda City 2020",
    "Toyota Yaris": "Toyota Vios XP150 2019",
    "Suzuki Cultus": "Suzuki Celerio 2015 front",
    "Suzuki WagonR": "Maruti Wagon R 2019 front",
    "Kia Sportage": "Kia Sportage QL",
    "Changan Alsvin": "Changan Alsvin front",
    "Suzuki Swift": "Suzuki Swift 2024",
    "Haval H6 HEV": "Haval H6 third generation",
    "Honda Civic": "Honda Civic FE 2022",
    "Hyundai Tucson": "Hyundai Tucson NX4",
    "MG HS": "MG HS 2019",
    "Kia Picanto": "Kia Picanto JA",
    "Toyota Fortuner": "Toyota Fortuner AN160",
    "BYD Atto 3": "BYD Atto 3",
}

# Hand-picked photos where the search picks the wrong car or generation
PINNED = {
    "Honda Civic": "File:2022 Honda Civic e-HEV RS.jpg",
    "Suzuki WagonR": "File:2019 Suzuki Karimun Wagon R GS (front), West Surabaya.jpg",
}


def get(params):
    url = API + "?" + urllib.parse.urlencode({**params, "format": "json"})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=20) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code != 429:
                raise
            time.sleep(5 * (attempt + 1))   # politely back off when rate-limited
    raise RuntimeError("Still rate-limited, try again in a minute")


def strip_html(s):
    return re.sub(r"<[^>]+>", "", s or "").strip()


# 1. Search for a photo per car (one small request each, spaced out)
files = dict(PINNED)
for car, query in QUERIES.items():
    if car in PINNED:
        continue
    res = get({"action": "query", "list": "search", "srnamespace": 6,
               "srsearch": f"{query} filetype:bitmap", "srlimit": 5})
    hits = [h["title"] for h in res["query"]["search"]
            if re.search(r"\.(jpe?g|png|webp)$", h["title"], re.I)
            and not re.search(r"rear|interior|engine|dashboard|messe|tuned", h["title"], re.I)]
    if hits:
        files[car] = hits[0]
        print(f"  found: {car} <- {hits[0]}")
    else:
        print(f"  none:  {car}")
    time.sleep(1)

# 2. Get URL, author and licence for all photos in one request
info = get({"action": "query", "titles": "|".join(files.values()), "prop": "imageinfo",
            "iiprop": "url|extmetadata", "iiurlwidth": 900})
by_title = {}
for p in info["query"]["pages"].values():
    if p.get("imageinfo"):
        by_title[p["title"]] = p["imageinfo"][0]
# The API may normalise titles (underscores -> spaces)
norm = {n["from"]: n["to"] for n in info["query"].get("normalized", [])}

photos = {}
for car, title in files.items():
    ii = by_title.get(norm.get(title, title))
    if not ii:
        continue
    meta = ii["extmetadata"]
    photos[car] = {
        "url": ii["thumburl"],
        "author": strip_html(meta.get("Artist", {}).get("value")) or "Unknown",
        "license": meta.get("LicenseShortName", {}).get("value", ""),
        "source": ii["descriptionurl"],
        "file": title,
    }

with open("photos.js", "w") as f:
    f.write("// Generated by tools/fetch_photos.py. Photos from Wikimedia Commons, credited on the page.\n")
    f.write("const photos = " + json.dumps(photos, indent=2, ensure_ascii=False) + ";\n")
print(f"\nWrote photos.js with {len(photos)} of {len(QUERIES)} cars.")
